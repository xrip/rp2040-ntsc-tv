#!/usr/bin/env python3
"""Execute the *actual* HDMI text PIO program against an independent oracle.

This small interpreter covers the documented RP2040 instructions used by the
program, including shift counters, blocking PULL and autopush backpressure.
It is a functional model, not a simulation of DMA/bus arbitration or HDMI
electrical timing. The optional --header also compares our assembled words
with the header generated by the SDK's pioasm.
"""

from __future__ import annotations

import argparse
from collections import deque
from pathlib import Path
import random
import re


ROOT = Path(__file__).resolve().parents[1]
MASK32 = (1 << 32) - 1
REGISTER = {"x": 1, "y": 2, "null": 3, "pc": 5, "isr": 6, "osr": 7}


def assemble(path: Path) -> tuple[list[int], int, int, int]:
    """Assemble only the instruction subset used here; reject unknown syntax."""
    labels: dict[str, int] = {}
    instructions: list[str] = []
    origin = None
    wrap_bottom, wrap_top = 0, None
    for raw in path.read_text().splitlines():
        line = raw.split(";", 1)[0].split("//", 1)[0].strip()
        if not line:
            continue
        if line.startswith(".program "):
            continue
        if line.startswith(".origin "):
            origin = int(line.split()[1], 0)
            continue
        if line == ".wrap_target":
            wrap_bottom = len(instructions)
            continue
        if line == ".wrap":
            wrap_top = len(instructions) - 1
            continue
        if line.endswith(":"):
            label = line[:-1].removeprefix("public ")
            assert label not in labels, f"duplicate label: {label}"
            labels[label] = len(instructions)
            continue
        assert not line.startswith("."), f"unsupported PIO directive: {line}"
        instructions.append(line)
    assert origin == 0, "OUT PC,1 requires absolute dispatch addresses 0 and 1"
    words = []
    for line in instructions:
        tokens = line.replace(",", " ").lower().split()
        op, *args = tokens
        if op == "jmp":
            condition = 0 if len(args) == 1 else {"!osre": 7}[args[0]]
            target = labels[args[-1]] if args[-1] in labels else int(args[-1], 0)
            assert 0 <= target < 32
            word = condition << 5 | target
        elif op in ("in", "out"):
            assert len(args) == 2
            count = int(args[1], 0)
            assert 1 <= count <= 32
            word = (0x4000 if op == "in" else 0x6000) | REGISTER[args[0]] << 5 | (count & 31)
        elif op == "mov":
            assert len(args) == 2
            word = 0xA000 | REGISTER[args[0]] << 5 | REGISTER[args[1]]
        elif op == "pull":
            assert args in ([], ["block"]), "only blocking, unconditional PULL is supported"
            word = 0x80A0
        else:
            raise AssertionError(f"unsupported PIO instruction: {line}")
        words.append(word)
    entry = labels.get("entry", 8)
    if wrap_top is None:
        wrap_top = len(words) - 1
    assert len(words) == 12, f"unexpected program length: {len(words)}"
    assert 0 <= entry < len(words)
    return words, entry, wrap_bottom, wrap_top


class PIO:
    """One SM with IN right/autopush24 and OUT right/manual pull/threshold24."""

    def __init__(self, program: tuple[list[int], int, int, int], palette_base: int):
        self.words, self.entry, self.wrap_bottom, self.wrap_top = program
        assert palette_base & 511 == 0
        self.pc = self.entry
        self.x = self.isr = self.osr = self.in_count = 0
        self.y = palette_base >> 9
        self.out_count = 32
        self.tx: deque[int] = deque()
        self.rx: deque[int] = deque()
        self.rx_capacity = 4
        self.cycles = 0
        self.executed = 0
        self.pull_stalls = self.push_stalls = 0
        self.push_counts: list[int] = []

    def source(self, code: int) -> int:
        if code == 1:
            return self.x
        if code == 2:
            return self.y
        if code == 3:
            return 0
        if code == 6:
            return self.isr
        if code == 7:
            return self.osr
        raise AssertionError(f"unsupported source {code}")

    def step(self) -> bool:
        self.cycles += 1
        assert 0 <= self.pc < len(self.words), f"PC left the program: {self.pc}"
        word = self.words[self.pc]
        assert word & 0x1F00 == 0, "unexpected delay/side-set bits"
        major, arg, count = word & 0xE000, word >> 5 & 7, word & 31
        next_pc = self.wrap_bottom if self.pc == self.wrap_top else self.pc + 1
        if major == 0:
            assert arg in (0, 7), f"unsupported JMP condition {arg}"
            if arg == 0 or self.out_count < 24:
                next_pc = count
        elif major == 0x4000:
            count = count or 32
            shifted_count = min(32, self.in_count + count)
            if shifted_count >= 24 and len(self.rx) == self.rx_capacity:
                # A stalled IN/autopush must not shift its source repeatedly.
                # Computing the pending operation only on acceptance is
                # observationally equivalent for this single-instruction SM.
                self.push_stalls += 1
                return False
            self.isr = ((self.isr >> count) | ((self.source(arg) & ((1 << count) - 1)) << (32 - count))) & MASK32
            self.in_count = shifted_count
            if shifted_count >= 24:
                self.rx.append(self.isr)
                self.push_counts.append(shifted_count)
                self.isr = self.in_count = 0
        elif major == 0x6000:
            count = count or 32
            value = self.osr & ((1 << count) - 1)
            self.osr >>= count
            self.out_count = min(32, self.out_count + count)
            if arg == 5:
                next_pc = value & 31
            else:
                assert arg == 3, f"unsupported OUT destination {arg}"
        elif word == 0x80A0:
            if not self.tx:
                self.pull_stalls += 1
                return False
            self.osr = self.tx.popleft()
            self.out_count = 0
        elif major == 0xA000:
            assert word & 0x18 == 0, "unsupported MOV transform"
            value = self.source(word & 7)
            if arg == 1:
                self.x = value
            elif arg == 6:
                self.isr = value
                self.in_count = 0
            else:
                raise AssertionError(f"unsupported MOV destination {arg}")
        else:
            raise AssertionError(f"unsupported instruction {word:#06x}")
        self.pc = next_pc
        self.executed += 1
        return True

    def one(self, word: int) -> tuple[list[int], list[int], int]:
        assert self.pc == self.entry and not self.tx and not self.rx
        self.tx.append(word)
        before = self.executed
        output = []
        self.push_counts.clear()
        while self.tx or self.pc != self.entry:
            assert self.executed - before < 100, "command did not terminate"
            self.step()
            if self.rx:
                output.append(self.rx.popleft())
        assert self.out_count == 24, f"wrong command length: {self.out_count} bits"
        assert self.in_count == 0 and self.isr == 0
        return output, self.push_counts.copy(), self.executed - before


def command(glyph: int, foreground: int, background: int, padding: int = 0) -> int:
    """Independent wire-format oracle; no production codec calls or tables."""
    assert 0 <= glyph <= 255 and 0 <= foreground < 32 and 0 <= background < 32
    result = foreground | background << 27 | (padding & 7) << 5
    for pixel in range(8):
        result |= ((glyph >> pixel & 1) | (pixel & 1) << 1) << (8 + 2 * pixel)
    assert result & 0x07000000 == 0
    return result


def expected(glyph: int, foreground: int, background: int, base: int) -> list[int]:
    return [base + ((foreground if glyph >> pixel & 1 else background) + 32 * (pixel & 1)) * 8
            for pixel in range(8)]


def reverse_byte(value: int) -> int:
    return int(f"{value:08b}"[::-1], 2)


def check_one(sm: PIO, glyph: int, foreground: int, background: int,
              base: int, padding: int = 0) -> None:
    output, counts, cycles = sm.one(command(glyph, foreground, background, padding))
    wanted = expected(glyph, foreground, background, base)
    assert output == wanted, (glyph, foreground, background, output, wanted)
    assert counts == [29 if glyph >> bit & 1 else 24 for bit in range(8)], counts
    assert cycles == 59, f"unexpected unobstructed cycles per 8-pixel command: {cycles}"


def exhaustive(program: tuple[list[int], int, int, int]) -> tuple[int, int]:
    base = 0x20001000
    sm = PIO(program, base)
    commands = 0
    # All pixel choices for every CGA foreground/background pair and for all
    # four H/V control codes, including foreground/control and background/control
    # mixtures. This also covers all 256 ordinary text attributes.
    for foreground in range(20):
        for background in range(20):
            for glyph in range(256):
                check_one(sm, glyph, foreground, background, base, glyph & 7)
                commands += 1
    # A complete glyph byte in either bit order, in both supported widths.
    # Width 40 consists of two independent eight-physical-pixel commands.
    for attribute in range(256):
        foreground, background = attribute & 15, attribute >> 4
        for original in range(256):
            for msb_first in (False, True):
                glyph = reverse_byte(original) if msb_first else original
                check_one(sm, glyph, foreground, background, base)
                commands += 1
                pixels = [(glyph >> bit & 1) for bit in range(8) for _ in range(2)]
                for start in (0, 8):
                    doubled = sum(pixels[start + bit] << bit for bit in range(8))
                    check_one(sm, doubled, foreground, background, base)
                    commands += 1
    # Base construction must not accidentally depend on a particular link map.
    for other_base in (0x20000000, 0x2003FE00, 0x2007FE00, 0x15000000):
        other = PIO(program, other_base)
        for glyph in (0, 1, 0x55, 0xAA, 0x80, 0xFF):
            for foreground, background in ((0, 15), (15, 0), (16, 19), (19, 16)):
                check_one(other, glyph, foreground, background, other_base)
                commands += 1
    return commands, commands * 8


def backpressure(program: tuple[list[int], int, int, int]) -> tuple[int, int, int]:
    """Random TX gaps and long full-RX intervals must preserve every pixel."""
    rng = random.Random(0x20402350)
    base = 0x20004000
    inputs = []
    wanted = []
    for index in range(1000):
        glyph, fg, bg = rng.randrange(256), rng.randrange(20), rng.randrange(20)
        inputs.append(command(glyph, fg, bg, index & 7))
        wanted.extend(expected(glyph, fg, bg, base))
    sm = PIO(program, base)
    output = []
    produced = 0
    # Deliberately begin with no input, then alternate long no-consumer windows
    # with slower/faster service. This is not a DMA cycle estimate.
    for cycle in range(1_000_000):
        if cycle > 50 and produced < len(inputs) and len(sm.tx) < 4 and rng.randrange(5) == 0:
            sm.tx.append(inputs[produced])
            produced += 1
        if cycle % 173 >= 100 and sm.rx and rng.randrange(3) == 0:
            output.append(sm.rx.popleft())
        sm.step()
        if produced == len(inputs) and not sm.tx and sm.pc == sm.entry and not sm.rx:
            break
    else:
        raise AssertionError("backpressure run failed to drain")
    assert output == wanted, "FIFO stall lost, duplicated, or reordered a pixel"
    assert sm.pull_stalls > 0 and sm.push_stalls > 0
    assert sm.executed == len(inputs) * 59
    assert sm.out_count == 24 and sm.in_count == 0
    return len(output), sm.pull_stalls, sm.push_stalls


def compare_header(path: Path, words: list[int]) -> None:
    contents = path.read_text()
    match = re.search(r"hdmi_text_program_instructions\[\]\s*=\s*\{(.*?)\};", contents, re.S)
    assert match is not None, "pioasm header does not contain hdmi_text_program_instructions"
    uncommented = re.sub(r"//[^\n]*", "", match.group(1))
    actual = [int(value, 16) for value in re.findall(r"0x[0-9a-fA-F]+", uncommented)]
    assert actual == words, f"pioasm and independent assembly differ: {actual!r} != {words!r}"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--program", type=Path, default=ROOT / "drivers/hdmi/hdmi_text.pio")
    parser.add_argument("--header", type=Path, help="optional actual SDK pioasm-generated header")
    args = parser.parse_args()
    program = assemble(args.program)
    if args.header is not None:
        compare_header(args.header, program[0])
    commands, pixels = exhaustive(program)
    stalled_pixels, pull_stalls, push_stalls = backpressure(program)
    print(f"PIO: {commands:,} exhaustive commands, {pixels:,} palette addresses; "
          f"{stalled_pixels:,} backpressured pixels; {pull_stalls:,} TX stalls, {push_stalls:,} RX stalls")
    print("PIO: exactly 59 unstalled instructions per eight pixels; "
          "functional verification only, not a DMA/bus timing measurement")


if __name__ == "__main__":
    main()
